/** Сфера жизни, под которую подбирается трактовка карты. */
export type LifeDomain = 'love' | 'work' | 'situation' | 'advice';

/** Вердикт «да/нет» с короткой оговоркой. */
export type YesNoVerdict = 'да' | 'скорее да' | 'нейтрально' | 'скорее нет' | 'нет';

export interface OrientedMeaning {
  /** Прямое положение. */
  up: string;
  /** Перевёрнутое положение. */
  rev: string;
}

export interface CardMeaning {
  /** Любовь, чувства, отношения, пара. */
  love: OrientedMeaning;
  /** Деньги, карьера, работа, проекты, ресурсы. */
  work: OrientedMeaning;
  /** Общий ход дела, диагностика ситуации, развитие событий. */
  situation: OrientedMeaning;
  /** Рекомендация: что сделать, на что опереться, чего избегать. */
  advice: OrientedMeaning;
  /** Ответ на закрытый вопрос. */
  yesno: { up: YesNoVerdict; rev: YesNoVerdict; note: string };
}

