/** Базовая сфера трактовки для каждого расклада. */
const SPREAD_DOMAIN: Record<string, LifeDomain> = {
  daily: 'advice',
  yesno: 'situation',
  question: 'situation',
  love: 'love',
  situation: 'situation',
  match: 'love',
  money: 'work',
  celtic: 'situation',
  year: 'situation',
};

/** Сфера расклада в целом (для шапки промпта). */
export function domainForSpread(spreadId: string): LifeDomain {
  return SPREAD_DOMAIN[spreadId] ?? 'situation';
}

/**
 * Сфера для КОНКРЕТНОЙ позиции: позиции вида «Совет»/«Рекомендация» всегда
 * читаются как совет, независимо от расклада. Остальные — по сфере расклада.
 */
export function domainForPosition(spreadId: string, positionTitle = ''): LifeDomain {
  if (/совет|рекоменд|что делать|действ/i.test(positionTitle)) return 'advice';
  return domainForSpread(spreadId);
}

/**
 * Точная трактовка карты под позицию расклада: берётся значение нужной сферы
 * и положения (прямое/перевёрнутое). Для «да/нет» добавляется вердикт.
 * Возвращает готовую строку для подстановки в промпт LLM.
 */
export function cardKnowledge(
  n: number,
  spreadId: string,
  positionTitle: string,
  reversed: boolean,
): string {
  const m = CARD_MEANINGS[n];
  if (!m) return '';
  const domain = domainForPosition(spreadId, positionTitle);
  const oriented = m[domain];
  const text = reversed ? oriented.rev : oriented.up;
  if (spreadId === 'yesno') {
    const verdict = reversed ? m.yesno.rev : m.yesno.up;
    return `${text} [Вердикт да/нет: ${verdict.toUpperCase()}. ${m.yesno.note}]`;
  }
  return text;
}

