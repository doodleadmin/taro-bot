function _hash(str: string): number {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function _mulberry(a: number): () => number {
  return function () {
    a |= 0;
    a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function _sunSign(dateStr: string): number | null {
  if (!dateStr) return null;
  const d = new Date(dateStr);
  if (isNaN(d.getTime())) return null;
  const m = d.getMonth() + 1, day = d.getDate();
  const ranges: [number, number, number][] = [
    [1,20,10],[2,19,11],[3,21,0],[4,20,1],[5,21,2],[6,21,3],
    [7,23,4],[8,23,5],[9,23,6],[10,23,7],[11,22,8],[12,22,9],
  ];
  const r = ranges[m - 1];
  return day >= r[1] ? r[2] : (r[2] + 11) % 12;
}

export interface NatalForm {
  name: string;
  date: string;
  time?: string;
  place?: string;
}

export interface NatalResult {
  sun: number;
  moon: number;
  asc: number;
  mercury: number;
  venus: number;
  mars: number;
  jupiter: number;
  saturn: number;
  planets: Array<{ key: string; sym: string; sign: number; deg: number }>;
  ascDeg: number;
  aspects: [number, number, string][];
  elements: { fire: number; earth: number; air: number; water: number };
}

export function computeNatal(form: NatalForm): NatalResult {
  const seedStr = `${form.date || ''}|${form.time || ''}|${form.name || ''}`;
  const rng = _mulberry(_hash(seedStr || 'seed'));
  const sunByDate = _sunSign(form.date);
  const sun = sunByDate != null ? sunByDate : (rng() * 12) | 0;
  const moon = (rng() * 12) | 0;
  const asc = (rng() * 12) | 0;
  const mercury = (rng() * 12) | 0;
  const venus = (rng() * 12) | 0;
  const mars = (rng() * 12) | 0;
  const jupiter = (rng() * 12) | 0;
  const saturn = (rng() * 12) | 0;

  const degOf = (sign: number) => sign * 30 + 8 + rng() * 14;
  const planets = [
    { key: 'sun',     sym: '☉', sign: sun,     deg: degOf(sun) },
    { key: 'moon',    sym: '☽', sign: moon,    deg: degOf(moon) },
    { key: 'mercury', sym: '☿', sign: mercury, deg: degOf(mercury) },
    { key: 'venus',   sym: '♀', sign: venus,   deg: degOf(venus) },
    { key: 'mars',    sym: '♂', sign: mars,    deg: degOf(mars) },
    { key: 'jupiter', sym: '♃', sign: jupiter, deg: degOf(jupiter) },
    { key: 'saturn',  sym: '♄', sign: saturn,  deg: degOf(saturn) },
  ];
  const ascDeg = asc * 30 + 4 + rng() * 22;

  const targets: [number, string][] = [[60,'h'],[120,'h'],[90,'t'],[180,'t']];
  const orb = 7;
  const aspects: [number, number, string, number][] = [];
  for (let i = 0; i < planets.length; i++) {
    for (let j = i + 1; j < planets.length; j++) {
      let diff = Math.abs(planets[i].deg - planets[j].deg) % 360;
      if (diff > 180) diff = 360 - diff;
      for (const [ang, type] of targets) {
        if (Math.abs(diff - ang) <= orb) {
          aspects.push([i, j, type, Math.abs(diff - ang)]);
          break;
        }
      }
    }
  }
  aspects.sort((a, b) => a[3] - b[3]);
  const topAspects = aspects.slice(0, 8).map(a => [a[0], a[1], a[2]] as [number, number, string]);

  const elPts = [sun, moon, asc, mercury, venus, mars, jupiter, saturn];
  const elements = { fire: 0, earth: 0, air: 0, water: 0 };
  elPts.forEach(s => {
    const el = SIGNS[s].el as ElementType;
    elements[el]++;
  });

  return { sun, moon, asc, mercury, venus, mars, jupiter, saturn, planets, ascDeg, aspects: topAspects, elements };
}

export function planetLine(lead: string, sign: number): string {
  const trait = SIGN_TRAIT[sign];
  const el = SIGNS[sign].el as ElementType;
  return `${lead} ${trait}. ${EL_NOTE[el]}`;
}
